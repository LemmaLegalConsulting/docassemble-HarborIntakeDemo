  await page.getByLabel('What would you like us to know?',{exact:true}).fill('My landlord sent a notice after I asked for a leaking ceiling to be repaired. I would like help understanding the notice and preparing for the hearing.');
  await next();
  await next('Yes');
  await page.getByLabel('Hearing or deadline date',{exact:true}).fill('2026-11-05');
  await next();
  await page.getByLabel('How many people are in your household, including you?',{exact:true}).fill('3');
  await page.getByLabel('Total monthly household income before taxes',{exact:true}).fill('2450');
  await next();
  await next('Yes');
